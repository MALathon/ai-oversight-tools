<script lang="ts">
	import { base } from '$app/paths';
	import { browser } from '$app/environment';
	import { onMount } from 'svelte';
	import { cfrToUrl } from '$lib/cfr-utils';

	interface Stage {
		id: string;
		name: string;
		shortName: string;
	}

	interface ModelType {
		id: string;
		name: string;
		description: string;
	}

	interface RiskSubdomain {
		id: string;
		code: string;
		name: string;
		shortName: string;
		domain: string;
		description: string;
		cfrReferences: string[];
	}

	interface Concern {
		id: string;
		riskSubdomain: string;
		stages: string[];
		category: string;
		reviewerText: string;
		investigatorText: string;
		canonical: string;
		cfrReferences: string[];
	}

	let stages: Stage[] = $state([]);
	let modelTypes: ModelType[] = $state([]);
	let riskSubdomains: RiskSubdomain[] = $state([]);
	let concernsBySubdomain: Record<string, Concern[]> = $state({});
	let modelTypeRelevance: Record<string, string[]> = $state({});

	let selectedStage: string = $state('');
	let selectedModelTypes: string[] = $state([]);
	let checkedItems: Set<string> = $state(new Set());
	let loading = $state(true);

	onMount(async () => {
		try {
			const [stagesRes, modelsRes, subdomainsRes, concernsRes, schemaRes] = await Promise.all([
				fetch(`${base}/data/stages.json`),
				fetch(`${base}/data/model-types.json`),
				fetch(`${base}/data/risk-subdomains.json`),
				fetch(`${base}/data/review-concerns.json`),
				fetch(`${base}/data/unified-schema.json`)
			]);

			const stagesData = await stagesRes.json();
			const modelsData = await modelsRes.json();
			const subdomainsData = await subdomainsRes.json();
			const concernsData = await concernsRes.json();
			const schemaData = await schemaRes.json();

			stages = stagesData.stages;
			modelTypes = modelsData.modelTypes;
			riskSubdomains = subdomainsData.riskSubdomains;

			// Group concerns by riskSubdomain
			const grouped: Record<string, Concern[]> = {};
			for (const concern of concernsData.concerns) {
				if (!grouped[concern.riskSubdomain]) {
					grouped[concern.riskSubdomain] = [];
				}
				grouped[concern.riskSubdomain].push(concern);
			}
			concernsBySubdomain = grouped;

			modelTypeRelevance = schemaData.modelTypeToSubdomainRelevance || {};
		} catch (e) {
			console.error('Failed to load data:', e);
		} finally {
			loading = false;
		}
	});

	function toggleModelType(id: string) {
		if (selectedModelTypes.includes(id)) {
			selectedModelTypes = selectedModelTypes.filter(m => m !== id);
		} else {
			selectedModelTypes = [...selectedModelTypes, id];
		}
	}

	function getRelevantSubdomains(): RiskSubdomain[] {
		if (selectedModelTypes.length === 0) {
			return riskSubdomains;
		}
		const relevantIds = new Set<string>();
		for (const modelType of selectedModelTypes) {
			const ids = modelTypeRelevance[modelType] || [];
			ids.forEach(id => relevantIds.add(id));
		}
		return riskSubdomains.filter(s => relevantIds.has(s.id));
	}

	function getConcernsForSubdomain(subdomainId: string): Concern[] {
		const concerns = concernsBySubdomain[subdomainId];
		if (!concerns) return [];
		if (!selectedStage) return concerns;
		return concerns.filter(c => c.stages.includes(selectedStage));
	}

	function toggleCheck(id: string) {
		const newSet = new Set(checkedItems);
		if (newSet.has(id)) {
			newSet.delete(id);
		} else {
			newSet.add(id);
		}
		checkedItems = newSet;
	}

	function getProgress(): { checked: number; total: number } {
		let total = 0;
		const relevantSubdomains = getRelevantSubdomains();
		for (const subdomain of relevantSubdomains) {
			const concerns = getConcernsForSubdomain(subdomain.id);
			total += concerns.length;
		}
		return { checked: checkedItems.size, total };
	}

	$effect(() => {
		// Reset checked items when filters change
		checkedItems = new Set();
	});

	function getSelectedStageName(): string {
		if (!selectedStage) return 'All Stages';
		const stage = stages.find(s => s.id === selectedStage);
		return stage ? stage.shortName : 'All Stages';
	}

	function resetChecklist() {
		checkedItems = new Set();
		selectedStage = '';
		selectedModelTypes = [];
	}

	async function exportDocx() {
		if (!browser) return;

		const { Document, Paragraph, TextRun, HeadingLevel, Packer, Table, TableRow, TableCell, BorderStyle, WidthType } = await import('docx');
		const { saveAs } = await import('file-saver');

		const children: any[] = [];
		const progress = getProgress();
		const stageName = getSelectedStageName();
		const modelNames = selectedModelTypes.length > 0
			? selectedModelTypes.map(id => modelTypes.find(m => m.id === id)?.name).filter(Boolean).join(', ')
			: 'All';

		children.push(
			new Paragraph({
				text: 'IRB AI Reviewer Checklist',
				heading: HeadingLevel.TITLE,
				spacing: { after: 100 }
			}),
			new Paragraph({
				children: [
					new TextRun({ text: 'Generated by AI Oversight Tools', italics: true, size: 24, color: '666666' })
				],
				spacing: { after: 400 }
			})
		);

		children.push(
			new Table({
				width: { size: 100, type: WidthType.PERCENTAGE },
				borders: {
					top: { style: BorderStyle.SINGLE, size: 1, color: 'CCCCCC' },
					bottom: { style: BorderStyle.SINGLE, size: 1, color: 'CCCCCC' },
					left: { style: BorderStyle.SINGLE, size: 1, color: 'CCCCCC' },
					right: { style: BorderStyle.SINGLE, size: 1, color: 'CCCCCC' },
					insideHorizontal: { style: BorderStyle.SINGLE, size: 1, color: 'CCCCCC' },
					insideVertical: { style: BorderStyle.SINGLE, size: 1, color: 'CCCCCC' }
				},
				rows: [
					new TableRow({
						children: [
							new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: 'Development Stage', bold: true })] })] }),
							new TableCell({ children: [new Paragraph(stageName)] })
						]
					}),
					new TableRow({
						children: [
							new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: 'Model Types', bold: true })] })] }),
							new TableCell({ children: [new Paragraph(modelNames)] })
						]
					}),
					new TableRow({
						children: [
							new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: 'Date Generated', bold: true })] })] }),
							new TableCell({ children: [new Paragraph(new Date().toLocaleDateString())] })
						]
					})
				]
			}),
			new Paragraph({ spacing: { after: 400 } })
		);

		const relevantSubdomains = getRelevantSubdomains();
		for (const subdomain of relevantSubdomains) {
			const concerns = getConcernsForSubdomain(subdomain.id);
			if (concerns.length === 0) continue;

			children.push(
				new Paragraph({
					children: [
						new TextRun({ text: `[${subdomain.code}] `, bold: true, color: '3B82F6' }),
						new TextRun({ text: subdomain.shortName, bold: true })
					],
					heading: HeadingLevel.HEADING_2,
					spacing: { before: 300, after: 100 }
				})
			);

			if (subdomain.cfrReferences.length > 0) {
				children.push(
					new Paragraph({
						children: [
							new TextRun({ text: 'CFR: ', bold: true, size: 20, color: '666666' }),
							new TextRun({ text: subdomain.cfrReferences.join(', '), size: 20, color: '666666' })
						],
						spacing: { after: 150 }
					})
				);
			}

			for (const concern of concerns) {
				const isChecked = checkedItems.has(concern.id);
				const checkbox = isChecked ? '\u2611' : '\u2610';
				const stageTags = concern.stages.map(s => s.replace('stage-', 'S')).join(' ');

				children.push(
					new Paragraph({
						children: [
							new TextRun({ text: `${checkbox} `, font: 'Segoe UI Symbol', size: 24 }),
							new TextRun({ text: concern.reviewerText, size: 22 }),
							new TextRun({ text: `  [${stageTags}]`, size: 18, color: '888888' })
						],
						spacing: { after: 80 },
						indent: { left: 360 }
					})
				);
			}
		}

		children.push(
			new Paragraph({ spacing: { before: 400 } }),
			new Paragraph({
				children: [
					new TextRun({ text: 'Progress Summary', bold: true, size: 28 })
				],
				heading: HeadingLevel.HEADING_2,
				spacing: { after: 100 }
			}),
			new Paragraph({
				children: [
					new TextRun({ text: `${progress.checked} of ${progress.total} items reviewed`, size: 24 }),
					new TextRun({ text: ` (${progress.total > 0 ? Math.round((progress.checked / progress.total) * 100) : 0}%)`, size: 24, color: '666666' })
				]
			})
		);

		const doc = new Document({
			sections: [{
				properties: {},
				children
			}]
		});

		const blob = await Packer.toBlob(doc);
		saveAs(blob, `IRB-Reviewer-Checklist-${stageName.replace(/\s+/g, '-')}-${new Date().toISOString().split('T')[0]}.docx`);
	}
</script>

