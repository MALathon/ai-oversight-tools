					Review again with different filters
				</button>
			</div>
		</div>
	{/if}

	<!-- Checklist -->
	<div class="checklist">
		{#each getRelevantSubdomains() as subdomain}
			{@const concerns = getConcernsForSubdomain(subdomain.id)}
			{#if concerns.length > 0}
				<div class="subdomain-section">
					<div class="subdomain-header">
						<div class="subdomain-title">
							<span class="code">{subdomain.code}</span>
							<h2>{subdomain.shortName}</h2>
						</div>
						{#if subdomain.cfrReferences.length > 0}
							<div class="cfr-refs">
								{#each subdomain.cfrReferences.slice(0, 2) as ref}
									{@const url = cfrToUrl(ref)}
									{#if url}
										<a class="cfr-badge cfr-link" href={url} target="_blank" rel="noopener">{ref}</a>
									{:else}
										<span class="cfr-badge">{ref}</span>
									{/if}
								{/each}
							</div>
						{/if}
					</div>

					<div class="prompts">
						{#each concerns as concern}
							<label class="prompt-item" class:checked={checkedItems.has(concern.id)}>
								<input
									type="checkbox"
									checked={checkedItems.has(concern.id)}
									onchange={() => toggleCheck(concern.id)}
								/>
								<span class="prompt-text">{concern.reviewerText}</span>
								<span class="stage-tags">
									{#each concern.stages as stg}
										<span class="stage-tag">{stg.replace('stage-', 'S')}</span>
									{/each}
								</span>
							</label>
						{/each}
					</div>
				</div>
			{/if}
		{/each}
	</div>
{/if}

